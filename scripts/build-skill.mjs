import { build } from 'esbuild';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const root = fileURLToPath(new URL('../', import.meta.url));
const { values } = parseArgs({ options: { check: { type: 'boolean', default: false } } });
const version = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8')).version;
const result = await build({
  absWorkingDir: root,
  entryPoints: ['packages/cli/src/main.ts'],
  outfile: 'tracecase.mjs',
  alias: { '@tracecase/core': resolve(root, 'packages/core/src/index.ts') },
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20.19',
  write: false,
  metafile: true,
  legalComments: 'inline',
  banner: {
    js: `// Tracecase ${version}. Generated by pnpm skill:build; edit the TypeScript sources instead.
const [major, minor] = process.versions.node.split('.').map(Number);
if (major < 20 || (major === 20 && minor < 19)) {
  console.error(JSON.stringify({ error: 'Tracecase requires Node.js 20.19 or newer.' }));
  process.exit(1);
}`,
  },
});

for (const output of Object.values(result.metafile.outputs)) {
  for (const imported of output.imports) {
    if (!imported.external || !imported.path.startsWith('node:')) {
      throw new Error(`Skill runtime must depend only on Node.js built-ins: ${imported.path}`);
    }
  }
}
const runtime = result.outputFiles[0].text;
if (runtime.includes(root)) throw new Error('Skill runtime contains an absolute build path');
const zodPackage = JSON.parse(
  await readFile(resolve(root, 'packages/core/node_modules/zod/package.json'), 'utf8'),
);
const zodLicense = await readFile(resolve(root, 'packages/core/node_modules/zod/LICENSE'), 'utf8');
const files = new Map([
  ['scripts/tracecase.mjs', runtime],
  [
    'scripts/THIRD_PARTY_NOTICES.txt',
    `Tracecase ${version} bundles Zod ${zodPackage.version}.\n\n${zodLicense.trim()}\n`,
  ],
]);

for (const [name, content] of files) {
  const path = resolve(root, 'skills/tracecase', name);
  if (values.check) {
    const actual = await readFile(path, 'utf8').catch(() => undefined);
    if (actual !== content) throw new Error(`${name} is missing or stale. Run pnpm skill:build.`);
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
  }
}
console.log(
  JSON.stringify({
    skill: 'tracecase',
    version,
    mode: values.check ? 'verified' : 'built',
    runtimeBytes: Buffer.byteLength(runtime),
    runtimeDependencies: 'Node.js built-ins only',
  }),
);
